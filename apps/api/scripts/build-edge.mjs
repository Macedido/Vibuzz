// Bundles the API for Supabase Edge Functions (Deno) into
// supabase/functions/vibuzz-api/bundle.js. npm dependencies stay external and
// are resolved by the function's deno.json import map.
//   npm run build:edge -w @vibuzz/api
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const outDir = join(root, 'supabase', 'functions', 'vibuzz-api');
mkdirSync(outDir, { recursive: true });

await build({
  stdin: { contents: "import { startEdge } from './src/edge';\nstartEdge();\n", resolveDir: join(here, '..'), loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  mainFields: ['module', 'main'],
  external: ['zod', '@supabase/supabase-js', 'hono', 'hono/*'],
  minify: true,
  lineLimit: 200,
  legalComments: 'none',
  banner: { js: '// Generated by apps/api/scripts/build-edge.mjs — do not edit. Source: apps/api/src' },
  outfile: join(outDir, 'bundle.js'),
});

writeFileSync(
  join(outDir, 'deno.json'),
  JSON.stringify(
    {
      imports: {
        zod: 'npm:zod@3.25.76',
        '@supabase/supabase-js': 'npm:@supabase/supabase-js@2.119.0',
        hono: 'npm:hono@4.13.16',
        'hono/': 'npm:/hono@4.13.16/',
      },
    },
    null,
    2,
  ) + '\n',
);
writeFileSync(join(outDir, 'index.ts'), "// Supabase Edge Function entry for the Vibuzz API (see bundle.js).\nimport './bundle.js';\n");
console.log('edge bundle written to', outDir);
